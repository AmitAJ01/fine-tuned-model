"""Incident diagnosis data schemas."""

from __future__ import annotations

from enum import Enum
from typing import List, Optional
from pydantic import BaseModel, Field


class IncidentCategory(str, Enum):
    INFRASTRUCTURE = "Infrastructure"
    DATABASE = "Database"
    NETWORK = "Network"
    APPLICATION = "Application"
    SECURITY = "Security"
    CI_CD = "CI/CD Pipeline"
    CI_CD_SHORT = "CI/CD"
    KUBERNETES = "Kubernetes / Container Orchestration"
    KUBERNETES_SHORT = "Kubernetes"
    UNKNOWN = "Unknown / Other"


class SeverityLevel(str, Enum):
    CRITICAL = "Critical"
    HIGH = "High"
    MEDIUM = "Medium"
    LOW = "Low"
    SEV1 = "SEV-1" # Critical outage, immediate data loss or security breach
    SEV2 = "SEV-2" # Major degradation of core service
    SEV3 = "SEV-3" # Moderate degradation, non-critical or workaround exists
    SEV4 = "SEV-4" # Minor issue, cosmetic or warning


class ModelTarget(str, Enum):
    BASELINE = "baseline"
    FINETUNED = "finetuned"


class IncidentRequest(BaseModel):
    """Input payload representing a raw incident or error logs."""
    log_text: str = Field(..., description="Raw log excerpt, stack trace, or incident description")
    system_context: Optional[str] = Field(
        default=None,
        description="Optional additional context (e.g. cloud provider, service name, architecture)",
    )
    model_target: ModelTarget = Field(
        default=ModelTarget.FINETUNED,
        description="Select whether to route to baseline or fine-tuned model",
    )
    temperature: float = Field(default=0.1, ge=0.0, le=1.0)
    max_tokens: int = Field(default=768, ge=64, le=2048)
    mock: bool = Field(default=False, description="Use simulation/mock mode for fast testing without GPU weights")


class IncidentReportPayload(BaseModel):
    """Canonical structured incident report generated by the diagnosis engine."""
    incident_category: IncidentCategory = Field(..., description="Categorization of the incident")
    severity_level: SeverityLevel = Field(..., description="Standardized severity rating")
    root_cause_analysis: str = Field(..., description="Detailed explanation of the underlying failure")
    contributing_factors: List[str] = Field(
        default_factory=list,
        description="External or environmental conditions that exacerbated the incident",
    )
    recommended_debugging_steps: List[str] = Field(
        default_factory=list,
        description="Actionable diagnostic and investigation commands or checks",
    )
    suggested_remediation_actions: List[str] = Field(
        default_factory=list,
        description="Immediate recovery actions and long-term preventive countermeasures",
    )


class IncidentDiagnosisResponse(BaseModel):
    """API response containing structured incident report and execution metadata."""
    report: Optional[IncidentReportPayload] = None
    model_used: str
    is_fine_tuned: bool
    latency_ms: float
    raw_response: str
    tokens_generated: Optional[int] = None
    json_valid: bool = True
    error_detail: Optional[str] = None


class DevOpsIncidentRecord(BaseModel):
    """Comprehensive dataset record schema for FineTuneOps."""
    id: str = Field(..., description="Unique incident identifier")
    category: str = Field(..., description="Incident category")
    severity: str = Field(..., description="Severity level: Low, Medium, High, Critical")
    incident_description: str = Field(..., description="Human-readable incident context")
    logs: str = Field(..., description="Raw log excerpt, stack trace, or event logs")
    root_cause: str = Field(..., description="Root cause explanation")
    contributing_factors: List[str] = Field(default_factory=list, description="Exacerbating factors")
    debugging_steps: List[str] = Field(default_factory=list, description="Diagnostic steps")
    recommended_actions: List[str] = Field(default_factory=list, description="Remediation steps")
    expected_output: IncidentReportPayload = Field(
        ...,
        description="Canonical structured report following IncidentReportPayload",
    )
    source_type: str = Field(
        default="synthetic",
        description="Origin: 'synthetic', 'public_postmortem', 'curated_benchmark', 'documentation_case'",
    )
    source_reference: Optional[str] = Field(
        default=None,
        description="Provenance reference, official doc, issue, or scenario ID",
    )

